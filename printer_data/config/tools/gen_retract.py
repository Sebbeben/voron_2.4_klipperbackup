#!/usr/bin/env python3
"""Retraction / stringing test: pairs of small towers, one retraction length per pair.

Pairs are stacked front -> back (first pair = --start). Within a pair the nozzle
travels 25 mm across open air using that pair's retraction, so strings between the
two towers of a pair belong to that value. Travel between pairs (along Y) uses a long
retraction so it does not add strings of its own. The front-left tower has a small
marker tab. Each pair is an exclude_object named retract_<mm>.

Mimics the Orca printer profile: retraction/deretraction 40 mm/s, z-hop 0.2,
travel 300 mm/s. Low enough (MAX_REMOTE_HEIGHT) to keep the plate for later tests.

Usage: gen_retract.py OUT.gcode [--start 0.2] [--end 1.2] [--step 0.2]
       [--temp 250] [--bed 105] [--flow 0.92] [--height 5.6]
"""
import argparse, math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import calib_common as cc

p = argparse.ArgumentParser()
p.add_argument("out")
p.add_argument("--start", type=float, default=0.2)
p.add_argument("--end", type=float, default=1.2)
p.add_argument("--step", type=float, default=0.2)
p.add_argument("--temp", type=int, default=250)
p.add_argument("--first-temp", type=int, default=255)
p.add_argument("--bed", type=int, default=105)
p.add_argument("--first-bed", type=int, default=110)
p.add_argument("--flow", type=float, default=0.92)
p.add_argument("--height", type=float, default=5.6)
p.add_argument("--fan", type=int, default=30)
p.add_argument("--zhop", type=float, default=0.2)
a = p.parse_args()

if a.height > cc.MAX_REMOTE_HEIGHT:
    sys.exit(f"--height over {cc.MAX_REMOTE_HEIGHT} mm: the toolhead would hit it during the next QGL")

W, H, H1 = 0.45, 0.2, 0.2
S = cc.spacing(W, H)
D = 8.0                       # tower diameter
GAP = 25.0                    # open-air travel inside a pair
PITCH = 16.0                  # pair spacing along Y
SEGS = 48
RET_F = 40 * 60
TRAVEL_F = 300 * 60
LONG_RET = 1.5

n = int(round((a.end - a.start) / a.step)) + 1
rets = [round(a.start + i * a.step, 3) for i in range(n)]
layers = int(round((a.height - H1) / H)) + 1

pair_w = 2 * D + GAP
foot_w = pair_w + 8           # + marker tab
foot_h = (n - 1) * PITCH + D + 6   # + purge line in front
fx, fy = cc.find_spot(foot_w, foot_h, a.height)
x_left = fx + 8 + D / 2       # centre of left towers
x_right = x_left + D + GAP
y0 = fy + 6 + D / 2

emm = cc.e_per_mm(W, H, a.flow)
out = []
w = out.append
w("; Retraction / stringing test - generated by gen_retract.py")
w(f"; retraction per pair, front -> back: {' '.join(str(r) for r in rets)} mm (z-hop {a.zhop}, 40 mm/s)")
for i, r in enumerate(rets):
    y = y0 + i * PITCH
    w(f"EXCLUDE_OBJECT_DEFINE NAME=retract_{r} CENTER={(x_left + x_right) / 2:.2f},{y:.2f} "
      f"POLYGON=[[{x_left - D/2:.2f},{y - D/2:.2f}],[{x_right + D/2:.2f},{y - D/2:.2f}],"
      f"[{x_right + D/2:.2f},{y + D/2:.2f}],[{x_left - D/2:.2f},{y + D/2:.2f}]]")
mk = (x_left - D / 2 - 6, y0 - 2)
w(f"EXCLUDE_OBJECT_DEFINE NAME=marker CENTER={mk[0] + 2:.2f},{mk[1] + 2:.2f} "
  f"POLYGON=[[{mk[0]:.2f},{mk[1]:.2f}],[{mk[0]+4:.2f},{mk[1]:.2f}],[{mk[0]+4:.2f},{mk[1]+4:.2f}],[{mk[0]:.2f},{mk[1]+4:.2f}]]")
w(cc.start_gcode(a.first_bed, a.first_temp, fx + 2, fy + 1.0, foot_w - 10,   # purge + wipe stay inside the footprint
                 obj_xy=((x_left + x_right) / 2, y0 + (n - 1) * PITCH / 2)))

state = {"retracted": 0.0, "z": 0.0}

def retract(length):
    w(f"G1 E-{length:.3f} F{RET_F}")
    state["retracted"] = length

def unretract():
    if state["retracted"]:
        w(f"G1 E{state['retracted']:.3f} F{RET_F}")
        state["retracted"] = 0.0

def travel(x, y, ret):
    retract(ret)
    w(f"G1 Z{state['z'] + a.zhop:.3f} F1800")
    w(f"G1 X{x:.3f} Y{y:.3f} F{TRAVEL_F}")
    w(f"G1 Z{state['z']:.3f} F1800")
    unretract()

def tower(cx, cy, f):
    """3 concentric loops, outside in; ends inside the tower."""
    for k in range(3):
        r = D / 2 - W / 2 - k * S
        seg = 2 * math.pi * r / SEGS
        if k:
            w(f"G1 X{cx + r:.3f} Y{cy:.3f} F{f}")
        for j in range(1, SEGS + 1):
            t = 2 * math.pi * j / SEGS
            w(f"G1 X{cx + r * math.cos(t):.3f} Y{cy + r * math.sin(t):.3f} E{seg * emm:.5f} F{f}")

for L in range(layers):
    z = H1 + L * H
    state["z"] = z
    w(f"; ---- layer {L + 1} z={z:.2f}")
    if L == 0:
        w("SET_VELOCITY_LIMIT ACCEL=500"); f = 30 * 60
    else:
        if L == 1:
            w(f"M104 S{a.temp}"); w(f"M140 S{a.bed}")
            w("SET_VELOCITY_LIMIT ACCEL=3000")
        if L == 2:
            w(f"M106 S{round(a.fan * 255 / 100)}")
        f = 60 * 60
    if L < 3:                                     # marker tab, 3 layers
        w("EXCLUDE_OBJECT_START NAME=marker")
        travel(mk[0] + W / 2, mk[1] + W / 2, LONG_RET)
        cur = (mk[0] + W / 2, mk[1] + W / 2)
        for px, py in [(mk[0] + 4 - W / 2, mk[1] + W / 2), (mk[0] + 4 - W / 2, mk[1] + 4 - W / 2),
                       (mk[0] + W / 2, mk[1] + 4 - W / 2), cur]:
            d = math.hypot(px - cur[0], py - cur[1])
            w(f"G1 X{px:.3f} Y{py:.3f} E{d * emm:.5f} F{f}"); cur = (px, py)
        w("EXCLUDE_OBJECT_END NAME=marker")
    for i, r in enumerate(rets):
        y = y0 + i * PITCH
        w(f"EXCLUDE_OBJECT_START NAME=retract_{r}")
        travel(x_left + D / 2 - W / 2, y, LONG_RET)   # between pairs: long retract
        tower(x_left, y, f)
        travel(x_right - D / 2 + W / 2, y, r)          # the tested open-air travel
        tower(x_right, y, f)
        w(f"EXCLUDE_OBJECT_END NAME=retract_{r}")

w(cc.end_gcode(a.bed))
open(a.out, "w").write("\n".join(out) + "\n")
cc.record((fx, fy, fx + foot_w, fy + foot_h), os.path.basename(a.out), a.height)
print(f"{a.out}: {n} pairs {rets[0]}..{rets[-1]} mm, {layers} layers, "
      f"footprint X {fx:.1f}-{fx + foot_w:.1f} Y {fy:.1f}-{fy + foot_h:.1f}")
