#!/usr/bin/env python3
"""Max volumetric flow test: a single-wall spiral (vase) cylinder whose flow rises
in steps with height. Look for the height where the wall turns matte/rough, gets
gaps or the extruder clicks; the step table at the top of the gcode (and printed
by this script) converts height to mm3/s. Use ~80 % of the last good value as
`filament_max_volumetric_speed` in Orca.

Placed automatically on a free bed spot (calib_common.find_spot), own start/purge,
bed stays hot afterwards.

Usage: gen_max_flow.py OUT.gcode [--start 10] [--end 40] [--step 2] [--step-height 2]
       [--temp 250] [--bed 105] [--diameter 60]
"""
import argparse, math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import calib_common as cc

p = argparse.ArgumentParser()
p.add_argument("out")
p.add_argument("--start", type=float, default=10.0)
p.add_argument("--end", type=float, default=40.0)
p.add_argument("--step", type=float, default=2.0)
p.add_argument("--step-height", type=float, default=2.0)
p.add_argument("--temp", type=int, default=250)
p.add_argument("--first-temp", type=int, default=255)
p.add_argument("--bed", type=int, default=105)
p.add_argument("--first-bed", type=int, default=110)
p.add_argument("--diameter", type=float, default=60.0)
p.add_argument("--flow", type=float, default=0.92, help="flow ratio (Orca filament_flow_ratio)")
p.add_argument("--fan", type=int, default=20)
a = p.parse_args()

W, H = 0.6, 0.3                      # line width / layer height
H1 = 0.25                            # first layer
BASE_LAYERS = 3                      # first layers at low speed (adhesion)
SEGS = 120
MAX_V = 300.0                        # printer max_velocity
R = a.diameter / 2
BRIM = 4
area = (W - H) * H + math.pi * (H / 2) ** 2
emm = cc.e_per_mm(W, H, a.flow)
emm1 = cc.e_per_mm(0.5, H1, a.flow)

steps = []
q = a.start
while q <= a.end + 1e-9:
    steps.append(round(q, 2)); q += a.step

base_top = H1 + (BASE_LAYERS - 1) * H
total_h = base_top + len(steps) * a.step_height
foot = a.diameter + 2 * (BRIM * 0.45 + 1)
PURGE_DY = 6.0
fx, fy = cc.find_spot(foot, foot + PURGE_DY)
cx, cy = fx + foot / 2, fy + PURGE_DY + foot / 2

table = []
for i, qv in enumerate(steps):
    z0 = base_top + i * a.step_height
    v = qv / area
    table.append((z0, z0 + a.step_height, qv, min(v, MAX_V)))

out = []
w = out.append
w("; Max volumetric flow test - generated by gen_max_flow.py")
w(f"; cylinder D{a.diameter} single wall {W} x {H}, flow ratio {a.flow}, {a.temp} C")
w("; height (mm)    flow (mm3/s)   speed (mm/s)")
for z0, z1, qv, v in table:
    w(f";  {z0:5.1f}-{z1:5.1f}     {qv:5.1f}          {v:5.0f}{'  (capped by max_velocity)' if qv / area > MAX_V else ''}")
w(f"EXCLUDE_OBJECT_DEFINE NAME=max_flow CENTER={cx:.2f},{cy:.2f} "
  f"POLYGON=[[{cx-R:.2f},{cy-R:.2f}],[{cx+R:.2f},{cy-R:.2f}],[{cx+R:.2f},{cy+R:.2f}],[{cx-R:.2f},{cy+R:.2f}]]")
w(cc.start_gcode(a.first_bed, a.first_temp, cx - 30, fy + 1.0))
w("EXCLUDE_OBJECT_START NAME=max_flow")

def pt(r, k):
    t = 2 * math.pi * k / SEGS
    return cx + r * math.cos(t), cy + r * math.sin(t)

# First layer: brim rings (outside in) + the wall ring, slow
w("SET_VELOCITY_LIMIT ACCEL=500")
w("G1 E-0.5 F2100")
x, y = pt(R + BRIM * 0.45, 0)
w(f"G1 X{x:.3f} Y{y:.3f} F18000")
w(f"G1 Z{H1} F600")
w("G1 E0.5 F2100")
seg1 = 2 * math.pi * R / SEGS
for ring in range(BRIM, -1, -1):
    r = R + ring * 0.45
    sl = 2 * math.pi * r / SEGS
    x, y = pt(r, 0)
    w(f"G1 X{x:.3f} Y{y:.3f} F1800")
    for k in range(1, SEGS + 1):
        x, y = pt(r, k)
        w(f"G1 X{x:.3f} Y{y:.3f} E{sl * emm1:.5f} F1800")

# Spiral wall: z rises continuously, H per revolution
w("SET_VELOCITY_LIMIT ACCEL=3000")
w(f"M104 S{a.temp}")
w(f"M140 S{a.bed}")
sl = 2 * math.pi * R / SEGS
z = H1
k = 0
fan_on = False
last_q = None
while z < total_h:
    z += H / SEGS
    k += 1
    if z < base_top:
        v = 30.0
        qv = None
    else:
        idx = min(int((z - base_top) / a.step_height), len(steps) - 1)
        qv = steps[idx]
        v = min(qv / area, MAX_V)
        if not fan_on:
            w(f"M106 S{round(a.fan * 255 / 100)}"); fan_on = True
    if qv != last_q:
        w(f"; flow {qv} mm3/s from z={z:.2f}" if qv else "; base layers")
        last_q = qv
    x, y = pt(R, k)
    w(f"G1 X{x:.3f} Y{y:.3f} Z{z:.4f} E{sl * emm:.5f} F{v * 60:.0f}")

w("EXCLUDE_OBJECT_END NAME=max_flow")
w(cc.end_gcode(a.bed))
open(a.out, "w").write("\n".join(out) + "\n")
cc.record((fx, fy, fx + foot, fy + foot + PURGE_DY), os.path.basename(a.out))
print(f"{a.out}: centre {cx:.1f},{cy:.1f}, height {total_h:.1f} mm")
for z0, z1, qv, v in table:
    print(f"  {z0:5.1f}-{z1:5.1f} mm  {qv:5.1f} mm3/s  {v:4.0f} mm/s")
