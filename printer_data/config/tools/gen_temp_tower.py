#!/usr/bin/env python3
"""Temperature tower: stacked 5 mm blocks, hottest at the bottom.

Each block: a 3-wall hollow box whose right side leans out 45 deg over the block
(overhang quality), plus a small pillar on the left that the nozzle travels to every
layer (stringing at that temperature). Block 1 (bottom) = --hot, then -step per block.

TALL: taller than MAX_REMOTE_HEIGHT, so it must be the LAST test on the plate - after it
is recorded, the other generators refuse to place anything until the layout is reset.

Usage: gen_temp_tower.py OUT.gcode [--hot 265] [--cold 235] [--step 5] [--flow 0.92]
"""
import argparse, math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import calib_common as cc

p = argparse.ArgumentParser()
p.add_argument("out")
p.add_argument("--hot", type=int, default=265)
p.add_argument("--cold", type=int, default=235)
p.add_argument("--step", type=int, default=5)
p.add_argument("--bed", type=int, default=105)
p.add_argument("--first-bed", type=int, default=110)
p.add_argument("--flow", type=float, default=0.92)
p.add_argument("--fan", type=int, default=20)
p.add_argument("--speed", type=float, default=60.0)
p.add_argument("--retract", type=float, default=0.5)
p.add_argument("--name", default="", help="material name for the label")
a = p.parse_args()

W, H = 0.45, 0.2
S = cc.spacing(W, H)
BLOCK_H = 5.0
LPB = int(round(BLOCK_H / H))            # layers per block
BOX_W, BOX_D = 30.0, 15.0
LEAN = BLOCK_H                           # 45 deg: grows BLOCK_H in X over a block
PIL_D, PIL_GAP = 5.0, 8.0
RET_F, TRAVEL_F = 40 * 60, 300 * 60

temps = list(range(a.hot, a.cold - 1, -a.step))
layers = LPB * len(temps)
height = layers * H
foot_w = PIL_D + PIL_GAP + BOX_W + LEAN + 2
ST = cc.STRIP                                            # title strip in front
foot_h = 6 + ST + BOX_D
fx, fy = cc.find_spot(foot_w, foot_h, height)
px, py = fx + 1 + PIL_D / 2, fy + 6 + ST + BOX_D / 2     # pillar centre
bx0, by0 = fx + 1 + PIL_D + PIL_GAP, fy + 6 + ST         # box front-left
# zone web: title strip in front, reaching back to the pillar centre so pillar and box are joined
web = [(fx, fy + 6, fx + foot_w, py)]
obst = [("circle", px, py, PIL_D / 2), ("rect", bx0, by0, bx0 + BOX_W, by0 + BOX_D)]
labels = [(f"T {a.name} {temps[0]}>{temps[-1]}".replace("  ", " "), fx + 1.0, fy + 6 + 1.0, 3.0, "left")]
emm = cc.e_per_mm(W, H, a.flow)

out = []
w = out.append
w("; Temperature tower - generated by gen_temp_tower.py")
w(f"; blocks bottom -> top ({BLOCK_H} mm each): {' '.join(str(t) for t in temps)} C")
w(f"EXCLUDE_OBJECT_DEFINE NAME=temp_tower CENTER={bx0 + BOX_W / 2:.2f},{by0 + BOX_D / 2:.2f} "
  f"POLYGON=[[{fx:.2f},{by0:.2f}],[{fx + foot_w:.2f},{by0:.2f}],[{fx + foot_w:.2f},{by0 + BOX_D:.2f}],[{fx:.2f},{by0 + BOX_D:.2f}]]")
w(cc.start_gcode(a.first_bed, temps[0], fx + 2, fy + 1.0, foot_w - 10,
                 obj_xy=(fx + foot_w / 2, by0 + BOX_D / 2)))
w("EXCLUDE_OBJECT_START NAME=temp_tower")

z = 0.0
def travel(x, y):
    w(f"G1 E-{a.retract} F{RET_F}")
    w(f"G1 Z{z + 0.2:.3f} F1800")
    w(f"G1 X{x:.3f} Y{y:.3f} F{TRAVEL_F}")
    w(f"G1 Z{z:.3f} F1800")
    w(f"G1 E{a.retract} F{RET_F}")

def loop(pts, f):
    cur = pts[0]
    for pt in pts[1:] + [pts[0]]:
        d = math.hypot(pt[0] - cur[0], pt[1] - cur[1])
        w(f"G1 X{pt[0]:.3f} Y{pt[1]:.3f} E{d * emm:.5f} F{f:.0f}"); cur = pt

for L in range(layers):
    z = H * (L + 1)
    blk, lb = divmod(L, LPB)
    w(f"; ---- layer {L + 1} z={z:.2f} block {blk + 1} ({temps[blk]} C)")
    if lb == 0 and blk > 0:
        w(f"M104 S{temps[blk]}")
        w(f"RESPOND MSG=\"Temp tower: block {blk + 1}/{len(temps)} {temps[blk]} C\"")
    if L == 0:
        w("SET_VELOCITY_LIMIT ACCEL=500"); f = 30 * 60
    else:
        if L == 1:
            w(f"M140 S{a.bed}"); w("SET_VELOCITY_LIMIT ACCEL=3000")
        if L == 3:
            w(f"M106 S{round(a.fan * 255 / 100)}")
        f = a.speed * 60
    w(f"G1 Z{z:.3f} F1200")
    if L == 0:
        w(cc.web_gcode(web, obst, z, H))
    elif L <= cc.LABEL_LAYERS:
        w(cc.label_gcode(labels, z))
    # pillar: 2 loops
    for k in range(2):
        r = PIL_D / 2 - W / 2 - k * S
        pts = [(px + r * math.cos(2 * math.pi * j / 24), py + r * math.sin(2 * math.pi * j / 24)) for j in range(24)]
        if k == 0:
            travel(*pts[0])
        else:
            w(f"G1 X{pts[0][0]:.3f} Y{pts[0][1]:.3f} F6000")
        loop(pts, f)
    # box: 3 walls, right side leaning out
    x1 = bx0 + BOX_W + LEAN * lb / LPB
    for k in range(3):
        d = W / 2 + k * S
        pts = [(bx0 + d, by0 + d), (x1 - d, by0 + d), (x1 - d, by0 + BOX_D - d), (bx0 + d, by0 + BOX_D - d)]
        if k == 0:
            travel(*pts[0])
        else:
            w(f"G1 X{pts[0][0]:.3f} Y{pts[0][1]:.3f} F6000")
        loop(pts, f)
    if L < 3:                              # solid floor for the box (first 3 layers)
        lo, hi = W / 2 + 2 * S + S * 0.85, BOX_D - (W / 2 + 2 * S + S * 0.85)
        m = int((hi - lo) / S) + 1
        xa, xb = bx0 + W / 2 + 2 * S + S * 0.85, x1 - (W / 2 + 2 * S + S * 0.85)
        cur = None
        for j in range(m):
            yy = by0 + lo + j * (hi - lo) / (m - 1)
            a_pt, b_pt = ((xa, yy), (xb, yy)) if j % 2 == 0 else ((xb, yy), (xa, yy))
            if cur is None:
                w(f"G1 X{a_pt[0]:.3f} Y{a_pt[1]:.3f} F6000")
            else:
                w(f"G1 X{a_pt[0]:.3f} Y{a_pt[1]:.3f} E{math.hypot(a_pt[0]-cur[0], a_pt[1]-cur[1]) * emm:.5f} F{f:.0f}")
            w(f"G1 X{b_pt[0]:.3f} Y{b_pt[1]:.3f} E{abs(b_pt[0]-a_pt[0]) * emm:.5f} F{f:.0f}")
            cur = b_pt

w("EXCLUDE_OBJECT_END NAME=temp_tower")
w(cc.end_gcode(a.bed))
open(a.out, "w").write("\n".join(out) + "\n")
cc.record((fx, fy, fx + foot_w, fy + foot_h), os.path.basename(a.out), height)
print(f"{a.out}: {len(temps)} blocks {temps[0]}..{temps[-1]} C, {height:.1f} mm tall, "
      f"footprint X {fx:.1f}-{fx + foot_w:.1f} Y {fy:.1f}-{fy + foot_h:.1f}")
