#!/usr/bin/env python3
"""Flow ratio test: a grid of solid tiles, each printed entirely at one flow ratio.

Uses the same extrusion math as OrcaSlicer, so the best tile's value is the
`filament_flow_ratio` to enter in the Orca filament profile (absolute, not a modifier).

Grid order: left -> right, front row first. The lowest-value tile has a small marker
square on its left side. Each tile is also an exclude_object named flow_<value>,
so Mainsail's object map shows the values.

Usage: gen_flow_tiles.py OUT.gcode [--start 0.88] [--end 1.02] [--step 0.01]
       [--bed 105] [--temp 250] [--first-temp 255] [--cols 5]
       gen_flow_tiles.py --reset-layout      (after clearing the plate)
"""
import argparse, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import calib_common as cc

p = argparse.ArgumentParser()
p.add_argument("out", nargs="?")
p.add_argument("--start", type=float, default=0.88)
p.add_argument("--end", type=float, default=1.02)
p.add_argument("--step", type=float, default=0.01)
p.add_argument("--bed", type=int, default=105)
p.add_argument("--first-bed", type=int, default=110)
p.add_argument("--temp", type=int, default=250)
p.add_argument("--first-temp", type=int, default=255)
p.add_argument("--cols", type=int, default=5)
p.add_argument("--tile", type=float, default=25.0)
p.add_argument("--layers", type=int, default=5)
p.add_argument("--fan", type=int, default=20, help="part fan %% from layer 4")
p.add_argument("--reset-layout", action="store_true")
a = p.parse_args()

if a.reset_layout:
    cc.reset_layout(); print("bed layout cleared"); sys.exit(0)
if not a.out:
    p.error("OUT.gcode required")

W, H = 0.45, 0.2                     # line width / layer height
S = cc.spacing(W, H)
T, GAP = a.tile, 6.0
n = int(round((a.end - a.start) / a.step)) + 1
flows = [round(a.start + i * a.step, 4) for i in range(n)]
rows = (n + a.cols - 1) // a.cols

grid_w = a.cols * T + (a.cols - 1) * GAP
grid_h = rows * T + (rows - 1) * GAP
MARK = 5.0                            # marker square left of the first tile
PURGE_DY = 6.0                        # purge line runs in front of the grid
foot_w, foot_h = grid_w + MARK + 3, grid_h + PURGE_DY
fx, fy = cc.find_spot(foot_w, foot_h, H * a.layers)
gx, gy = fx + MARK + 3, fy + PURGE_DY  # grid origin (front-left of first tile)

tiles = []
for i, f in enumerate(flows):
    r, c = divmod(i, a.cols)
    x0 = gx + c * (T + GAP)
    y0 = gy + r * (T + GAP)
    tiles.append((f, x0, y0))

out = []
w = out.append
w(f"; Flow ratio tiles - generated by gen_flow_tiles.py")
w(f"; flows (left->right, front row first): {' '.join(str(f) for f in flows)}")
w(f"; footprint X {fx:.1f}-{fx + foot_w:.1f} Y {fy:.1f}-{fy + foot_h:.1f}, line {W} x {H}, spacing {S:.3f}")
for f, x0, y0 in tiles:
    w(f"EXCLUDE_OBJECT_DEFINE NAME=flow_{f} CENTER={x0 + T/2:.2f},{y0 + T/2:.2f} "
      f"POLYGON=[[{x0:.2f},{y0:.2f}],[{x0+T:.2f},{y0:.2f}],[{x0+T:.2f},{y0+T:.2f}],[{x0:.2f},{y0+T:.2f}]]")
mx0, my0 = gx - MARK - 3, gy
w(f"EXCLUDE_OBJECT_DEFINE NAME=marker CENTER={mx0 + MARK/2:.2f},{my0 + MARK/2:.2f} "
  f"POLYGON=[[{mx0:.2f},{my0:.2f}],[{mx0+MARK:.2f},{my0:.2f}],[{mx0+MARK:.2f},{my0+MARK:.2f}],[{mx0:.2f},{my0+MARK:.2f}]]")
w(cc.start_gcode(a.first_bed, a.first_temp, gx, fy + 1.0, min(60.0, grid_w), obj_xy=(gx + grid_w / 2, gy + grid_h / 2)))

state = {"x": None, "y": None}

def travel(x, y):
    w("G1 E-0.5 F2100")
    w("G91\nG1 Z0.4 F1200\nG90")
    w(f"G1 X{x:.3f} Y{y:.3f} F18000")
    w("G91\nG1 Z-0.4 F1200\nG90")
    w("G1 E0.5 F2100")

def ext(x, y, f, flow, x_from, y_from):
    d = ((x - x_from) ** 2 + (y - y_from) ** 2) ** 0.5
    w(f"G1 X{x:.3f} Y{y:.3f} E{d * cc.e_per_mm(W, H, flow):.5f} F{f:.0f}")

def square(x0, y0, size, flow, layer, wall_f, fill_f):
    """2 perimeters + zigzag infill (X lines on odd layers, Y lines on even)."""
    for k in range(2):
        d = W / 2 + k * S
        pts = [(x0 + d, y0 + d), (x0 + size - d, y0 + d), (x0 + size - d, y0 + size - d), (x0 + d, y0 + size - d)]
        if k == 0:
            travel(*pts[0])
        else:
            w(f"G1 X{pts[0][0]:.3f} Y{pts[0][1]:.3f} F6000")
        cur = pts[0]
        for pt in pts[1:] + [pts[0]]:
            ext(pt[0], pt[1], wall_f, flow, *cur); cur = pt
    inner = W / 2 + S + S * 0.85         # infill line centres (15 % overlap with perimeter)
    lo, hi = inner, size - inner
    along_x = layer % 2 == 1
    m = int((hi - lo) / S) + 1
    step = (hi - lo) / (m - 1) if m > 1 else 0
    cur = None
    for j in range(m):
        o = lo + j * step
        if along_x:
            a_pt, b_pt = (x0 + lo, y0 + o), (x0 + hi, y0 + o)
        else:
            a_pt, b_pt = (x0 + o, y0 + lo), (x0 + o, y0 + hi)
        if j % 2:
            a_pt, b_pt = b_pt, a_pt
        if cur is None:
            w(f"G1 X{a_pt[0]:.3f} Y{a_pt[1]:.3f} F6000")
        else:
            ext(a_pt[0], a_pt[1], fill_f, flow, *cur)
        ext(b_pt[0], b_pt[1], fill_f, flow, *a_pt)
        cur = b_pt

for layer in range(1, a.layers + 1):
    z = H * layer
    w(f"; ---- layer {layer} z={z:.2f}")
    w(f"G1 Z{z:.2f} F1200")
    if layer == 1:
        w("SET_VELOCITY_LIMIT ACCEL=500")
        wall_f = fill_f = 40 * 60
    else:
        if layer == 2:
            w(f"M104 S{a.temp}")
            w(f"M140 S{a.bed}")
        w("SET_VELOCITY_LIMIT ACCEL=" + ("2000" if layer == a.layers else "3000"))
        wall_f, fill_f = 60 * 60, 80 * 60
    if layer == 4:
        w(f"M106 S{round(a.fan * 255 / 100)}")
    if layer <= 3:                        # marker: 3 layers
        w("EXCLUDE_OBJECT_START NAME=marker")
        square(mx0, my0, MARK, 0.95, layer, wall_f, fill_f)
        w("EXCLUDE_OBJECT_END NAME=marker")
    for f, x0, y0 in tiles:
        w(f"EXCLUDE_OBJECT_START NAME=flow_{f}")
        square(x0, y0, T, f, layer, wall_f, fill_f)
        w(f"EXCLUDE_OBJECT_END NAME=flow_{f}")

w(cc.end_gcode(a.bed))
open(a.out, "w").write("\n".join(out) + "\n")
cc.record((fx, fy, fx + foot_w, fy + foot_h), os.path.basename(a.out), H * a.layers)
print(f"{a.out}: {n} tiles {flows[0]}..{flows[-1]}, footprint X {fx:.1f}-{fx+foot_w:.1f} "
      f"Y {fy:.1f}-{fy+foot_h:.1f}")
