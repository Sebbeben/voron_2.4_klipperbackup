#!/usr/bin/env python3
"""Bridge test: unsupported bridges of 10..50 mm between pairs of pillars, one column per bridge
flow ratio (default 0.85 and 0.95). Everything stands on a one-layer web: the bridge length is
raised left of each row, the flow ratio above each column, the title in front.

Pillars 6 x 6 mm, 2.6 mm tall; then one bridge layer (lines from pillar to pillar, Orca-style
round cross-section, bridge speed/fan/acceleration as in the Orca profile) and one normal layer
on top of the deck. Read it from below: the longest bridge that is straight and not sagging, and
which flow column looks better. Low enough (MAX_REMOTE_HEIGHT) to keep the plate for later tests.

Usage: gen_bridge.py OUT.gcode [--temp 250] [--bed 105] [--flows 0.85,0.95] [--speed 25]
       [--bridge-fan 60] [--name ABS]
"""
import argparse, math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import calib_common as cc

p = argparse.ArgumentParser()
p.add_argument("out")
p.add_argument("--temp", type=int, default=250)
p.add_argument("--first-temp", type=int, default=255)
p.add_argument("--bed", type=int, default=105)
p.add_argument("--first-bed", type=int, default=110)
p.add_argument("--flow", type=float, default=0.99, help="filament flow ratio (Orca filament_flow_ratio)")
p.add_argument("--flows", default="0.85,0.95", help="bridge flow ratios, one column each")
p.add_argument("--lengths", default="10,20,30,40,50")
p.add_argument("--speed", type=float, default=25.0, help="bridge speed mm/s (Orca bridge_speed)")
p.add_argument("--fan", type=int, default=20, help="part fan %% for the pillars")
p.add_argument("--bridge-fan", type=int, default=60, help="part fan %% during the bridge layer")
p.add_argument("--name", default="", help="material name for the label")
a = p.parse_args()

flows = [float(v) for v in a.flows.split(",") if v.strip()]
lengths = [float(v) for v in a.lengths.split(",") if v.strip()]
W, H1, H = 0.45, 0.2, 0.2
S = cc.spacing(W, H)
PIL = 6.0                       # pillar size (X and Y) = deck width
PIL_LAYERS = 13                 # 2.6 mm
PITCH = 10.0                    # row pitch (Y)
LC, GC, ST = 8.0, 6.0, cc.STRIP  # length label column, gap between columns (with a web strip), strips
CW = PIL + max(lengths) + PIL    # column width
BRIDGE_W = 0.40                 # bridge line diameter (round, Orca non-thick bridges)
BRIDGE_S = 0.45                 # bridge line spacing
RET, RET_F, TRAVEL_F = 0.5, 40 * 60, 300 * 60

height = H1 + (PIL_LAYERS - 1) * H + 2 * H
foot_w = LC + len(flows) * CW + (len(flows) - 1) * GC
foot_h = 6 + ST + len(lengths) * PITCH - (PITCH - PIL) + 1.0 + ST
fx, fy = cc.find_spot(foot_w, foot_h, height)
y_rows = [fy + 6 + ST + i * PITCH for i in range(len(lengths))]       # front edge of each row
col_x = [fx + LC + c * (CW + GC) for c in range(len(flows))]          # left edge of each column
y_top = y_rows[-1] + PIL

pillars = []    # (x0, y0) of every pillar
bridges = []    # (flow, x_left_pillar, x_right_pillar, y0)
for c, bf in enumerate(flows):
    for i, L in enumerate(lengths):
        xl = col_x[c]
        xr = xl + PIL + L
        pillars += [(xl, y_rows[i]), (xr, y_rows[i])]
        bridges.append((bf, xl, xr, y_rows[i]))

# web: title strip in front, length column, a strip left of every further column, flow header behind
yb = fy + 6
web = [(fx, yb, fx + foot_w, y_rows[0] + 1.0), (fx, yb, col_x[0] + 1.0, y_top),
       (fx, y_top - 1.0, fx + foot_w, y_top + 1.0 + ST)]
for c in range(1, len(flows)):
    web.append((col_x[c] - GC + 1.5, yb, col_x[c] + 1.0, y_top))
obst = [("rect", x0, y0, x0 + PIL, y0 + PIL) for x0, y0 in pillars]
labels = [(f"{L:g}", fx + 0.8, y_rows[i] + PIL / 2 - 1.75, 3.5, "left") for i, L in enumerate(lengths)]
labels += [(f"F{bf:g}", col_x[c] + 1.0, y_top + 2.0, 3.5, "left") for c, bf in enumerate(flows)]
labels.append((f"BRIDGE {a.name} {a.temp}".replace("  ", " "), fx + 0.8, yb + 1.0, 3.5, "left"))

emm = cc.e_per_mm(W, H, a.flow)
emm1 = cc.e_per_mm(W, H1, a.flow)
out = []
w = out.append
w("; Bridge test - generated by gen_bridge.py")
w(f"; lengths front->back {' '.join(f'{L:g}' for L in lengths)} mm, columns left->right bridge flow "
  f"{' '.join(f'{bf:g}' for bf in flows)}, bridge speed {a.speed:g} mm/s, fan {a.bridge_fan} %")
w(f"EXCLUDE_OBJECT_DEFINE NAME=bridges CENTER={fx + foot_w / 2:.2f},{(y_rows[0] + y_top) / 2:.2f} "
  f"POLYGON=[[{fx:.2f},{yb:.2f}],[{fx + foot_w:.2f},{yb:.2f}],[{fx + foot_w:.2f},{y_top + ST + 1:.2f}],"
  f"[{fx:.2f},{y_top + ST + 1:.2f}]]")
w(cc.start_gcode(a.first_bed, a.first_temp, fx + 2, fy + 1.0, min(foot_w - 10, 100.0),
                 obj_xy=(fx + foot_w / 2, (y_rows[0] + y_top) / 2)))
w("EXCLUDE_OBJECT_START NAME=bridges")

state = {"z": 0.0}


def travel(x, y):
    z = state["z"]
    w(f"G1 E-{RET} F{RET_F}")
    w(f"G1 Z{z + 0.4:.3f} F1800")
    w(f"G1 X{x:.3f} Y{y:.3f} F{TRAVEL_F}")
    w(f"G1 Z{z:.3f} F1800")
    w(f"G1 E{RET} F{RET_F}")


def solid_square(x0, y0, size, layer, f, e):
    """2 perimeters + zigzag infill, alternating X/Y lines per layer."""
    cur = None
    for k in range(2):
        d = W / 2 + k * S
        pts = [(x0 + d, y0 + d), (x0 + size - d, y0 + d), (x0 + size - d, y0 + size - d), (x0 + d, y0 + size - d)]
        if k == 0:
            travel(*pts[0])
        else:
            w(f"G1 X{pts[0][0]:.3f} Y{pts[0][1]:.3f} F6000")
        cur = pts[0]
        for pt in pts[1:] + [pts[0]]:
            w(f"G1 X{pt[0]:.3f} Y{pt[1]:.3f} E{math.hypot(pt[0] - cur[0], pt[1] - cur[1]) * e:.5f} F{f:.0f}")
            cur = pt
    lo, hi = W / 2 + S + S * 0.85, size - (W / 2 + S + S * 0.85)
    m = int((hi - lo) / S) + 1
    for j in range(m):
        o = lo + j * (hi - lo) / max(1, m - 1)
        if layer % 2:
            pa, pb = (x0 + lo, y0 + o), (x0 + hi, y0 + o)
        else:
            pa, pb = (x0 + o, y0 + lo), (x0 + o, y0 + hi)
        if j % 2:
            pa, pb = pb, pa
        w(f"G1 X{pa[0]:.3f} Y{pa[1]:.3f} E{math.hypot(pa[0] - cur[0], pa[1] - cur[1]) * e:.5f} F{f:.0f}")
        w(f"G1 X{pb[0]:.3f} Y{pb[1]:.3f} E{math.hypot(pb[0] - pa[0], pb[1] - pa[1]) * e:.5f} F{f:.0f}")
        cur = pb


for L in range(PIL_LAYERS):
    z = H1 + L * H
    state["z"] = z
    w(f"; ---- pillar layer {L + 1} z={z:.2f}")
    w(f"G1 Z{z:.3f} F1200")
    if L == 0:
        w("SET_VELOCITY_LIMIT ACCEL=500")
        f = 30 * 60
        w(cc.web_gcode(web, obst, z, H1))
    else:
        if L == 1:
            w(f"M104 S{a.temp}")
            w(f"M140 S{a.bed}")
            w("SET_VELOCITY_LIMIT ACCEL=3000")
        if L == 2:
            w(f"M106 S{round(a.fan * 255 / 100)}")
        f = 60 * 60
        if L <= cc.LABEL_LAYERS:
            w(cc.label_gcode(labels, z))
    for x0, y0 in pillars:
        solid_square(x0, y0, PIL, L, f, emm1 if L == 0 else emm)

# bridge layer: lines along X from 1 mm inside the left pillar to 1 mm inside the right pillar
z = H1 + PIL_LAYERS * H
state["z"] = z
w(f"; ---- bridge layer z={z:.2f}")
w(f"G1 Z{z:.3f} F1200")
w(f"M106 S{round(a.bridge_fan * 255 / 100)}")
w("SET_VELOCITY_LIMIT ACCEL=1000")
area = math.pi * (BRIDGE_W / 2) ** 2
for bf, xl, xr, y0 in bridges:
    eb = area / cc.FIL_AREA * a.flow * bf
    n = int((PIL - BRIDGE_W) / BRIDGE_S) + 1
    xa, xb = xl + 1.0, xr + PIL - 1.0
    for j in range(n):
        yy = y0 + BRIDGE_W / 2 + j * (PIL - BRIDGE_W) / max(1, n - 1)
        s0, s1 = (xa, xb) if j % 2 == 0 else (xb, xa)
        if j == 0:
            travel(s0, yy)
        else:
            w(f"G1 X{s0:.3f} Y{yy:.3f} F3000")
        w(f"G1 X{s1:.3f} Y{yy:.3f} E{abs(s1 - s0) * eb:.5f} F{a.speed * 60:.0f}")

# one normal layer on top of each deck (lines across, so the deck stays flat)
z += H
state["z"] = z
w(f"; ---- deck top layer z={z:.2f}")
w(f"G1 Z{z:.3f} F1200")
w(f"M106 S{round(a.fan * 255 / 100)}")
w("SET_VELOCITY_LIMIT ACCEL=3000")
for bf, xl, xr, y0 in bridges:
    x0, x1 = xl + W / 2, xr + PIL - W / 2
    n = int((PIL - W) / S) + 1
    for j in range(n):
        yy = y0 + W / 2 + j * (PIL - W) / max(1, n - 1)
        s0, s1 = (x0, x1) if j % 2 == 0 else (x1, x0)
        if j == 0:
            travel(s0, yy)
        else:
            w(f"G1 X{s0:.3f} Y{yy:.3f} F3000")
        w(f"G1 X{s1:.3f} Y{yy:.3f} E{abs(s1 - s0) * emm:.5f} F{40 * 60}")

w("EXCLUDE_OBJECT_END NAME=bridges")
w(cc.end_gcode(a.bed))
open(a.out, "w").write("\n".join(out) + "\n")
cc.record((fx, fy, fx + foot_w, fy + foot_h), os.path.basename(a.out), height)
print(f"{a.out}: bridges {' '.join(f'{L:g}' for L in lengths)} mm x flows {' '.join(f'{bf:g}' for bf in flows)}, "
      f"{height:.1f} mm tall, footprint X {fx:.1f}-{fx + foot_w:.1f} Y {fy:.1f}-{fy + foot_h:.1f}")
