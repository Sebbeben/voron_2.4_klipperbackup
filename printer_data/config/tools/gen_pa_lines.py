#!/usr/bin/env python3
"""Generate a pressure-advance line test (one first-layer line per PA value).

Each line: slow 20 mm -> fast 50 mm -> slow 20 mm. With correct PA the line has the
same width through both speed changes (no blob at slow->fast end, no gap at fast start).
Line 0 (front, lowest Y) is PA_START. Every 4th line has a short marker stub on the left.

Usage: gen_pa_lines.py OUT.gcode [--start 0] [--end 0.08] [--step 0.005]
       [--bed 105] [--temp 250] [--flow 0.92]
"""
import argparse, math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import calib_common as cc

p = argparse.ArgumentParser()
p.add_argument("out")
p.add_argument("--start", type=float, default=0.0)
p.add_argument("--end", type=float, default=0.08)
p.add_argument("--step", type=float, default=0.005)
p.add_argument("--bed", type=int, default=105)
p.add_argument("--temp", type=int, default=250)
p.add_argument("--flow", type=float, default=0.92)
p.add_argument("--fast", type=float, default=120.0, help="fast segment mm/s")
p.add_argument("--first-temp", type=int, default=255)
p.add_argument("--first-bed", type=int, default=110)
p.add_argument("--restore-pa", type=float, default=0.045, help="PA set again at the end")
p.add_argument("--fixed", action="store_true", help="old fixed position + PRINT_START (plate must be empty)")
a = p.parse_args()

W, H = 0.5, 0.25                      # line width / height
FIL = math.pi * (1.75 / 2) ** 2
AREA = (W - H) * H + math.pi * (H / 2) ** 2   # Slic3r/Orca extrusion cross-section
E_MM = AREA / FIL * a.flow
SLOW, FAST = 20 * 60, a.fast * 60
DY = 5.0
SEG = (20.0, 50.0, 20.0)
RETRACT, RET_F = 0.5, 35 * 60

n = int(round((a.end - a.start) / a.step)) + 1
pas = [round(a.start + i * a.step, 4) for i in range(n)]
if a.fixed:
    X0, Y0 = 130.0, 120.0
else:                                    # free spot; purge line 6 mm in front
    fw, fh = 15 + sum(SEG) + 2, (n - 1) * DY + 2 + 8
    fx, fy = cc.find_spot(fw, fh)
    X0, Y0 = fx + 15, fy + 8
y_max = Y0 + (n - 1) * DY
x_min, x_max = X0 - 15, X0 + sum(SEG)

g = []
w = g.append
w("; Pressure advance line test - generated by gen_pa_lines.py")
w("; PA values front->back: " + " ".join(str(v) for v in pas))
w(f"EXCLUDE_OBJECT_DEFINE NAME=pa_lines CENTER={(x_min+x_max)/2:.1f},{(Y0+y_max)/2:.1f} "
  f"POLYGON=[[{x_min:.1f},{Y0-2:.1f}],[{x_max:.1f},{Y0-2:.1f}],[{x_max:.1f},{y_max+2:.1f}],[{x_min:.1f},{y_max+2:.1f}]]")
if a.fixed:
    w(f"PRINT_START BED={a.bed} EXTRUDER={a.temp} CHAMBER=0")
else:
    w(cc.start_gcode(a.first_bed, a.first_temp, fx + 2, fy + 1.0, fw - 10, obj_xy=(fx + fw / 2, fy + fh / 2)))
    w(f"M104 S{a.temp}")
    w(f"M140 S{a.bed}")
    w(f"M109 S{a.temp}")
w("G90")
w("M83")
w("M107")
w("SET_VELOCITY_LIMIT ACCEL=3000")
w("EXCLUDE_OBJECT_START NAME=pa_lines")
w(f"G1 E-{RETRACT} F{RET_F}")
w("G1 Z1 F600")

def line(x0, y, length, f):
    return f"G1 X{x0+length:.3f} Y{y:.3f} E{length*E_MM:.5f} F{f:.0f}"

for i, pa in enumerate(pas):
    y = Y0 + i * DY
    w(f"; line {i}: PA {pa}")
    w(f"SET_PRESSURE_ADVANCE ADVANCE={pa}")
    if i % 4 == 0:                        # marker stub
        w(f"G1 X{x_min:.3f} Y{y:.3f} F12000")
        w(f"G1 Z{H} F600")
        w(f"G1 E{RETRACT} F{RET_F}")
        w(line(x_min, y, 8.0, SLOW))
        w(f"G1 E-{RETRACT} F{RET_F}")
        w("G1 Z1 F600")
    w(f"G1 X{X0:.3f} Y{y:.3f} F12000")
    w(f"G1 Z{H} F600")
    w(f"G1 E{RETRACT} F{RET_F}")
    x = X0
    for length, f in zip(SEG, (SLOW, FAST, SLOW)):
        w(line(x, y, length, f)); x += length
    w(f"G1 E-{RETRACT} F{RET_F}")
    w("G1 Z1 F600")

w("EXCLUDE_OBJECT_END NAME=pa_lines")
w(f"SET_PRESSURE_ADVANCE ADVANCE={a.restore_pa}")
if a.fixed:
    w("PRINT_END")
else:
    w(cc.end_gcode(a.bed))
    cc.record((fx, fy, fx + fw, fy + fh), os.path.basename(a.out))
open(a.out, "w").write("\n".join(g) + "\n")
print(f"{a.out}: {n} lines, PA {pas[0]}..{pas[-1]}, E/mm {E_MM:.5f}, Y {Y0}..{y_max}")
